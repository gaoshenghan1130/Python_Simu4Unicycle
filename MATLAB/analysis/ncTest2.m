%% 9. Final summary

fprintf('\nFinal valid states:\n');
fprintf([ ...
    '------------------------------------------------', ...
    '--------------------------------------------\n']);

for j = 1:num_cases
    final_state = results(j).z(end, :);

    fprintf( ...
        ['k = %+7.1f N/m, ', ...
         'c = %+6.1f N*s/m, ', ...
         't = %.6f s, ', ...
         'theta = %+12.6f rad, ', ...
         'r = %+12.6f m, ', ...
         'max|F| = %.6f N'], ...
        results(j).k, ...
        results(j).velocity_gain, ...
        results(j).t(end), ...
        final_state(1), ...
        final_state(3), ...
        max(abs(results(j).F)));

    if results(j).stopped_early
        fprintf('  [stopped early]\n');
    else
        fprintf('  [completed]\n');
    end
end