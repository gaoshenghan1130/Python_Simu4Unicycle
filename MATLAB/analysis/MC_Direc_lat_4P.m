        2, ...
        5, ...
        10, ...
        15, ...
        20, ...
        25
    ];

    line_levels = line_levels( ...
        line_levels <= maximum_angle ...
    );

    if ~isempty(line_levels)

        contour( ...
            ax, ...
            K_theta_grid, ...
            K_r_grid, ...
            theta_eq_deg, ...
            line_levels, ...
            'LineColor', [0.18, 0.18, 0.18], ...
            'LineWidth', 0.65, ...
            'HandleVisibility', 'off' ...
        );
    end

    %% Rod-limit equilibrium contour

    rod_angle = ...
        equilibrium_data.theta_rod_limit_deg;

    if rod_angle <= maximum_angle

        % White underlay.
        contour( ...
            ax, ...
            K_theta_grid, ...
            K_r_grid, ...
            theta_eq_deg, ...
            [rod_angle, rod_angle], ...
            'LineColor', 'w', ...
            'LineWidth', 4.0, ...
            'HandleVisibility', 'off' ...
        );

        [~, h_rod_limit] = contour( ...
            ax, ...
            K_theta_grid, ...
            K_r_grid, ...
            theta_eq_deg, ...
            [rod_angle, rod_angle], ...
            '--', ...
            'LineColor', [0.90, 0.10, 0.05], ...
            'LineWidth', 2.4 ...
        );

        h_rod_limit.DisplayName = sprintf( ...
            'Nonzero equilibrium at |r| = %.0f cm', ...
            100*equilibrium_data.rod_limit ...
        );
    end

    %% Boundary where the nonzero branch emerges

    if ~isempty(equilibrium_data.K_theta_boundary)

        % White underlay.
        plot( ...
            ax, ...
            equilibrium_data.K_theta_boundary, ...
            equilibrium_data.K_r_boundary, ...
            '-', ...
            'Color', 'w', ...
            'LineWidth', 4.5, ...
            'HandleVisibility', 'off' ...
        );

        h_boundary = plot( ...
            ax, ...
            equilibrium_data.K_theta_boundary, ...
            equilibrium_data.K_r_boundary, ...
            'k--', ...
            'LineWidth', 2.2, ...
            'DisplayName', ...
            'Nonzero-equilibrium boundary' ...
        );
    end
end
