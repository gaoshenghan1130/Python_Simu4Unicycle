%% Best available nonzero equilibrium

% Selection priority:
%   1. all simulated and equilibrium limits satisfied;
%   2. force-limit-valid and equilibrium-force-valid;
%   3. nonlinear stable;
%   4. any sampled gain set with a positive nonzero equilibrium.
%
% This fallback hierarchy guarantees that the best available gain set is
% still printed when no sample satisfies the rod limit. The printed
% selection class states clearly which constraints were retained.

equilibrium_force_valid_idx = ...
    abs(force_equilibrium_record) ...
    <= force_limit + 1e-9;

equilibrium_rod_valid_idx = ...
    abs(r_equilibrium_record) ...
    <= rod_limit + 1e-9;

strict_candidate_idx = ...
    force_valid_idx ...
    & rod_valid_idx ...
    & isfinite(theta_equilibrium_record) ...
    & equilibrium_force_valid_idx ...
    & equilibrium_rod_valid_idx;

force_candidate_idx = ...
    force_valid_idx ...
    & isfinite(theta_equilibrium_record) ...
    & equilibrium_force_valid_idx;

stable_candidate_idx = ...
    nonlinear_stable_idx ...
    & isfinite(theta_equilibrium_record);

equilibrium_candidate_idx = ...
    isfinite(theta_equilibrium_record);

if any(strict_candidate_idx)

    best_candidate_idx = strict_candidate_idx;
    selection_name = ...
        'all force and rod limits satisfied';

elseif any(force_candidate_idx)

    best_candidate_idx = force_candidate_idx;
    selection_name = ...
        'force-limit valid; rod limit relaxed';

elseif any(stable_candidate_idx)

    best_candidate_idx = stable_candidate_idx;
    selection_name = ...
        'nonlinear stable; force and rod limits relaxed';

elseif any(equilibrium_candidate_idx)

    best_candidate_idx = equilibrium_candidate_idx;
    selection_name = ...
        'nonzero equilibrium exists; simulation limits relaxed';

else

    best_candidate_idx = false(N, 1);
    selection_name = ...
        'no positive nonzero equilibrium found';

end

fprintf('\nBest available nonzero equilibrium\n');

fprintf( ...
    'Selection class:         %s\n', ...
    selection_name ...
);

fprintf( ...
    'Candidates in class:     %d\n', ...
    sum(best_candidate_idx) ...
);

if any(best_candidate_idx)

    candidate_indices = find(best_candidate_idx);

    [best_theta_eq, local_best_idx] = max( ...
        theta_equilibrium_record(best_candidate_idx) ...
    );

    best_sample_idx = ...
        candidate_indices(local_best_idx);

    best_K = K_samples(best_sample_idx, :);

    % Convert the generalized-speed gains to the ordinary derivative
    % gains because sigma1 = theta_dot and
    % sigma2 = r_dot - R*theta_dot:
    %
    % K_dtheta = K_sigma1 - R*K_sigma2,
    % K_dr     = K_sigma2.
    best_K_dtheta = ...
        best_K(3) - par.R*best_K(4);
    best_K_dr = best_K(4);

    best_r_eq = r_equilibrium_record(best_sample_idx);
    best_force_eq = ...
        force_equilibrium_record(best_sample_idx);

    % This residual checks the static feedback balance
    % F_eq = -K_theta*theta_eq - K_r*r_eq.
    best_equilibrium_residual = ...
        -best_K(1)*best_theta_eq ...
        -best_K(2)*best_r_eq ...
        -best_force_eq;

    fprintf( ...
        'Sample index:           %d\n', ...
        best_sample_idx ...
    );

    fprintf( ...
        'K_theta:                %.9g\n', ...
        best_K(1) ...
    );

    fprintf( ...
        'K_r:                    %.9g\n', ...
        best_K(2) ...
    );

    fprintf( ...
        'K_dtheta:               %.9g\n', ...
        best_K_dtheta ...
    );

    fprintf( ...
        'K_dr:                   %.9g\n', ...
        best_K_dr ...
    );

    fprintf( ...
        'Equilibrium theta:      +/- %.9f deg\n', ...
        best_theta_eq*180/pi ...
    );

    fprintf( ...
        ['Equilibrium r:          +/- %.9f m ' ...
        '(%.6f cm)\n'], ...
        best_r_eq, ...
        100*best_r_eq ...
    );

    fprintf( ...
        'Equilibrium |F|:        %.9f N\n', ...
        abs(best_force_eq) ...
    );

    fprintf( ...
        'Equilibrium residual:   %.3e N\n', ...
        best_equilibrium_residual ...
    );

    fprintf( ...
        'Simulated max |theta|:  %.9f deg\n', ...
        max_theta_record(best_sample_idx)*180/pi ...
    );

    fprintf( ...
        'Simulated final theta:  %.9f deg\n', ...
        final_theta_record(best_sample_idx)*180/pi ...
    );

    fprintf( ...
        'Simulated max |r|:      %.6f cm\n', ...
        100*max_r_record(best_sample_idx) ...
    );

    fprintf( ...
        'Simulated max |F|:      %.9f N\n', ...
        max_force_record(best_sample_idx) ...
    );

else

    best_sample_idx = [];

    fprintf( ...
        ['No sampled gain set has a positive nonzero ' ...
        'equilibrium inside the search-angle range.\n'] ...
    );

end

