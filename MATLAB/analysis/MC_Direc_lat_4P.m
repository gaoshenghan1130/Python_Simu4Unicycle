%% Local functions

function F = PDController(z, K, R)

    theta = z(1);
    theta_dot = z(2);
    r = z(3);
    r_dot = z(4);

    sigma1 = theta_dot;
    sigma2 = r_dot - R*theta_dot;

    x = [
        theta;
        r;
        sigma1;
        sigma2
    ];

    F = -K*x;
end

function x = modelToControllerState(z, R)

    theta = z(:, 1);
    theta_dot = z(:, 2);
    r = z(:, 3);
    r_dot = z(:, 4);

    sigma1 = theta_dot;
    sigma2 = r_dot - R*theta_dot;

    x = [
        theta, ...
        r, ...
        sigma1, ...
        sigma2
    ];
end

function [value, isterminal, direction] = ...
    fallDetector(~, z, fall_limit)

    value = fall_limit - abs(z(1));
    isterminal = 1;
    direction = 0;
end

function equilibrium_data = ...
    buildEquilibriumContourData( ...
        gain_min, ...
        gain_max, ...
        par, ...
        fall_limit, ...
        rod_limit ...
    )

    m = par.m_rod;
    g = par.g;
    R = par.R;
    G = par.G;

    equilibrium_factor = ...
        (G + m*g*R)/(m*g);

    grid_size = 300;

    K_theta_values = linspace( ...
        gain_min(1), ...
        gain_max(1), ...
        grid_size ...
    );

    K_r_values = linspace( ...
        gain_min(2), ...
        gain_max(2), ...
        grid_size ...
    );

    [K_theta_grid, K_r_grid] = meshgrid( ...
        K_theta_values, ...
        K_r_values ...
    );

    theta_search_max = min( ...
        fall_limit, ...
        pi/2 - 1e-5 ...
    );

    theta_eq_grid = ...
        solvePositiveNonzeroEquilibrium( ...
            K_theta_grid, ...
            K_r_grid, ...
            equilibrium_factor, ...
            m, ...
            g, ...
            theta_search_max ...
        );

    theta_eq_grid_deg = ...
        theta_eq_grid*180/pi;

    theta_rod_limit = atan( ...
        rod_limit/equilibrium_factor ...
    );

    theta_rod_limit_deg = ...
        theta_rod_limit*180/pi;

    % Boundary where the nonzero equilibrium branch
    % emerges from theta = 0:
    %
    % K_theta + equilibrium_factor*K_r + m*g = 0.

    K_r_boundary = linspace( ...
        gain_min(2), ...
        gain_max(2), ...
        600 ...
    );

    K_theta_boundary = ...
        -equilibrium_factor*K_r_boundary ...
        -m*g;

    boundary_valid = ...
        K_theta_boundary >= gain_min(1) ...
        & K_theta_boundary <= gain_max(1);

    equilibrium_data.K_theta_grid = ...
        K_theta_grid;

    equilibrium_data.K_r_grid = ...
        K_r_grid;

    equilibrium_data.theta_eq_grid_deg = ...
        theta_eq_grid_deg;

    equilibrium_data.factor = ...
        equilibrium_factor;

    equilibrium_data.theta_rod_limit_deg = ...
        theta_rod_limit_deg;

    equilibrium_data.rod_limit = ...
        rod_limit;

    equilibrium_data.K_r_boundary = ...
        K_r_boundary(boundary_valid);

    equilibrium_data.K_theta_boundary = ...
        K_theta_boundary(boundary_valid);
end

function theta_eq = ...
    solvePositiveNonzeroEquilibrium( ...
        K_theta, ...
        K_r, ...
        equilibrium_factor, ...
        m, ...
        g, ...
        theta_max ...
    )

    theta_eq = nan(size(K_theta));

    % Derivative of the equilibrium equation at theta = 0:
    %
    % q'(0) = K_theta
    %       + equilibrium_factor*K_r
    %       + m*g.

    origin_slope = ...
        K_theta ...
        + equilibrium_factor*K_r ...
        + m*g;

    q_at_max = ...
        K_theta*theta_max ...
        + K_r*equilibrium_factor*tan(theta_max) ...
        + m*g*sin(theta_max);

    % A positive nonzero equilibrium lies inside the
    % search interval when the equation initially decreases
    % from zero and becomes nonnegative before theta_max.

    valid_idx = ...
        origin_slope < 0 ...
        & q_at_max >= 0;

    if ~any(valid_idx, 'all')
        return;
    end

    theta_lower = zeros(size(K_theta));

    theta_upper = ...
        theta_max*ones(size(K_theta));

    % Vectorized bisection.
    for iteration = 1:60

        theta_mid = ...
            0.5*(theta_lower + theta_upper);

        q_mid = ...
            K_theta.*theta_mid ...
            + K_r.*equilibrium_factor.*tan(theta_mid) ...
            + m*g*sin(theta_mid);

        lower_update = ...
            valid_idx ...
            & q_mid <= 0;

        upper_update = ...
            valid_idx ...
            & q_mid > 0;

        theta_lower(lower_update) = ...
            theta_mid(lower_update);

        theta_upper(upper_update) = ...
            theta_mid(upper_update);
    end

    theta_eq(valid_idx) = ...
        0.5*( ...
            theta_lower(valid_idx) ...
            + theta_upper(valid_idx) ...
        );
end

