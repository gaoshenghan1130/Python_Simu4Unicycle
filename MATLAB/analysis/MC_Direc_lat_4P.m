clear;
clc;
close all;

addpath('param/', 'model/');
par = LatParam();

%% Settings

force_limit = 27.6;
rod_limit = 0.10;
fall_limit = 27*pi/180;

rng(1);

N = 10000;

gain_min = [-900, 150, -150, 10];
gain_max = [-150, 1000, -5, 200];

K_samples = gain_min ...
    + rand(N, 4).*(gain_max - gain_min);

nonlinear_stable_idx = false(N, 1);
force_valid_idx = false(N, 1);
rod_valid_idx = false(N, 1);
simulation_failed_idx = false(N, 1);

max_theta_record = nan(N, 1);
final_theta_record = nan(N, 1);
max_r_record = nan(N, 1);
max_force_record = nan(N, 1);

%% Closed-loop nonzero-equilibrium contours
%
% Static mechanical equilibrium:
%
% F_eq = m*g*sin(theta_eq)
%
% r_eq = equilibrium_factor*tan(theta_eq)
%
% Linear feedback at equilibrium:
%
% F_eq = -K_theta*theta_eq - K_r*r_eq
%
% Therefore:
%
% K_theta*theta_eq
% + K_r*equilibrium_factor*tan(theta_eq)
% + m*g*sin(theta_eq) = 0
%
% theta_eq = 0 is always an equilibrium.
% The calculation below finds the positive nonzero equilibrium.

equilibrium_data = buildEquilibriumContourData( ...
    gain_min, ...
    gain_max, ...
    par, ...
    fall_limit, ...
    rod_limit ...
);

% Evaluate the positive nonzero equilibrium for every sampled gain set.
% These values are used below to identify the feasible gain set that
% permits the largest equilibrium angle.

theta_search_max = min( ...
    fall_limit, ...
    pi/2 - 1e-5 ...
);

theta_equilibrium_record = ...
    solvePositiveNonzeroEquilibrium( ...
        K_samples(:, 1), ...
        K_samples(:, 2), ...
        equilibrium_data.factor, ...
        par.m_rod, ...
        par.g, ...
        theta_search_max ...
    );

r_equilibrium_record = ...
    equilibrium_data.factor ...
    .* tan(theta_equilibrium_record);

force_equilibrium_record = ...
    par.m_rod*par.g ...
    .* sin(theta_equilibrium_record);

fprintf('\nClosed-loop equilibrium information\n');

fprintf( ...
    'Equilibrium factor:        %.6f m\n', ...
    equilibrium_data.factor ...
);

fprintf( ...
    'Rod-limit angle:           %.6f deg\n', ...
    equilibrium_data.theta_rod_limit_deg ...
);

%% Monte Carlo simulation

z0 = [
    0.9*pi/180;
    0;
    0;
    0
];

tspan = [0, 15];

ode_options = odeset( ...
    'Events', @(t, z) fallDetector(t, z, fall_limit), ...
    'RelTol', 1e-7, ...
    'AbsTol', 1e-9 ...
);

for i = 1:N

    K = K_samples(i, :);

    controller = @(t, z, par) PDController( ...
        z, ...
        K, ...
        par.R ...
    );

    try
        [t_out, z_out] = ode45( ...
            @(t, z) LatModelAppell( ...
                t, ...
                z, ...
                par, ...
                controller ...
            ), ...
            tspan, ...
            z0, ...
            ode_options ...
        );

        if isempty(z_out) || any(~isfinite(z_out), 'all')
            simulation_failed_idx(i) = true;
            continue;
        end

        x_out = modelToControllerState( ...
            z_out, ...
            par.R ...
        );

        theta_out = x_out(:, 1);
        r_out = x_out(:, 2);

        F_out = -(x_out*K.');

        max_theta = max(abs(theta_out));
        final_theta = abs(theta_out(end));
        max_r = max(abs(r_out));
        max_force = max(abs(F_out));

        simulation_completed = ...
            t_out(end) >= tspan(end) - 1e-6;

        theta_valid = ...
            simulation_completed ...
            && max_theta < 20*pi/180 ...
            && final_theta < 5*pi/180;

        force_valid = ...
            theta_valid ...
            && max_force <= force_limit + 1e-9;

        rod_valid = ...
            theta_valid ...
            && max_r <= rod_limit + 1e-9;

        nonlinear_stable_idx(i) = theta_valid;
        force_valid_idx(i) = force_valid;
        rod_valid_idx(i) = rod_valid;

        max_theta_record(i) = max_theta;
        final_theta_record(i) = final_theta;
        max_r_record(i) = max_r;
        max_force_record(i) = max_force;

    catch
        simulation_failed_idx(i) = true;
    end

    if mod(i, 100) == 0 || i == N
        fprintf( ...
            'Monte Carlo progress: %d / %d\n', ...
            i, ...
            N ...
        );
    end
end

