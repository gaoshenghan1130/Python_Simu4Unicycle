%% Open-loop eigenvectors
%
% Different lengths are used so that eigenvectors with identical
% theta-r directions remain visible.

eigenvector_colors = lines(4);

eigenvector_lengths = [
    0.16;
    0.14;
    0.12;
    0.10
];

eigenvalue_text = cell(4, 1);

for i = 1:4

    arrow = ...
        eigenvector_lengths(i)*V_theta_r(:, i);

    lambda_real = ...
        real(lambda_open_loop(i));

    lambda_imag = ...
        imag(lambda_open_loop(i));

    if abs(lambda_imag) < 1e-10

        lambda_value_text = ...
            sprintf( ...
                '%+.4f', ...
                lambda_real);

    else

        lambda_value_text = ...
            sprintf( ...
                '%+.4f%+.4fi', ...
                lambda_real, ...
                lambda_imag);
    end

    % Construct LaTeX outside sprintf so backslashes are not
    % interpreted as sprintf escape sequences.
    eigenvector_label = [
        '$v_{', ...
        num2str(i), ...
        '},\;\lambda=', ...
        lambda_value_text, ...
        '$'
    ];

    eigenvalue_text{i} = [
        '$\lambda_{', ...
        num2str(i), ...
        '}=', ...
        lambda_value_text, ...
        '$'
    ];

    % Positive direction
    quiver( ...
        0, ...
        0, ...
        arrow(1), ...
        arrow(2), ...
        0, ...
        'Color', eigenvector_colors(i, :), ...
        'LineWidth', 2.2, ...
        'MaxHeadSize', 0.25, ...
        'DisplayName', eigenvector_label);

    % Negative direction
    quiver( ...
        0, ...
        0, ...
        -arrow(1), ...
        -arrow(2), ...
        0, ...
        'Color', eigenvector_colors(i, :), ...
        'LineWidth', 2.2, ...
        'MaxHeadSize', 0.25, ...
        'HandleVisibility', 'off');

    text( ...
        arrow(1), ...
        arrow(2), ...
        sprintf('  v_%d', i), ...
        'Color', eigenvector_colors(i, :), ...
        'FontWeight', 'bold', ...
        'Interpreter', 'tex');
end

