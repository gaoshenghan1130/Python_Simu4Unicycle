%% Local functions

function F_command = fixed_gain_error_controller( ...
    z_true, ...
    K, ...
    total_angle_error, ...
    total_gyro_error, ...
    use_force_limit, ...
    force_limit_N ...
)

    z_measured = [
        z_true(1) + total_angle_error;
        z_true(2) + total_gyro_error;
        z_true(3);
        z_true(4)
    ];

    F_command = -K*z_measured;

    if use_force_limit

        F_command = max( ...
            -force_limit_N, ...
            min(force_limit_N, F_command) ...
        );
    end
end

function z_next = rk4_step( ...
    t, ...
    z, ...
    dt, ...
    par, ...
    controller ...
)

    k1 = LatModel_SignCorrection( ...
        t, ...
        z, ...
        par, ...
        controller ...
    );

    k2 = LatModel_SignCorrection( ...
        t + dt/2, ...
        z + dt*k1/2, ...
        par, ...
        controller ...
    );

    k3 = LatModel_SignCorrection( ...
        t + dt/2, ...
        z + dt*k2/2, ...
        par, ...
        controller ...
    );

    k4 = LatModel_SignCorrection( ...
        t + dt, ...
        z + dt*k3, ...
        par, ...
        controller ...
    );

    z_next = z + ...
        dt*(k1 + 2*k2 + 2*k3 + k4)/6;
end