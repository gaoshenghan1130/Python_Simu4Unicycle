%% Local functions

function result = simulateGainTuple( ...
        par, C_eq, z0, tspan, ode_options, ...
        k1, d1, k_theta, d_theta, force_guard, balance)

    result.max_force = NaN;
    result.max_r = NaN;
    result.completed = false;
    result.event_stopped = false;
    result.stationary = false;
    result.origin_converged = false;
    result.failed = false;
    result.final_time = tspan(1);
    result.final_theta = NaN;
    result.final_r = NaN;
    result.tail_max_theta_dot = NaN;
    result.tail_max_r_dot = NaN;
    result.tail_max_surface_error = NaN;
    result.tail_max_surface_speed = NaN;
    result.tail_max_theta = NaN;
    result.tail_max_r = NaN;

    controller = @(t, z, p) equilibriumCurveController( ...
        t, z, p, C_eq, ...
        k1, d1, k_theta, d_theta, force_guard);

    model_rhs = @(t, z) LatModel_SignCorrection( ...
        t, z, par, controller);

    try
        [t, z, event_time] = ode45( ...
            model_rhs, ...
            tspan, ...
            z0, ...
            ode_options);
    catch
        result.failed = true;
        return;
    end

    if isempty(t) || isempty(z) || ...
       any(~isfinite(t(:))) || any(~isfinite(z(:)))

        result.failed = true;
        return;
    end

    result.final_time = t(end);
    result.final_theta = z(end, 1);
    result.final_r = z(end, 3);
    result.event_stopped = ~isempty(event_time);

    theta = z(:, 1);
    theta_dot = z(:, 2);
    r = z(:, 3);
    r_dot = z(:, 4);

    cos_theta = cos(theta);

    if any(~isfinite(cos_theta)) || any(abs(cos_theta) < 1e-6)
        result.failed = true;
        return;
    end

    s = r - C_eq*tan(theta);
    s_dot = r_dot - ...
        C_eq./(cos_theta.^2).*theta_dot;

    F = ...
        par.m_rod*par.g*sin(theta) ...
        - k1*s ...
        - d1*s_dot ...
        + k_theta*theta ...
        + d_theta*theta_dot;

    if any(~isfinite(F)) || any(abs(F) > force_guard)
        result.failed = true;
        return;
    end

    result.max_force = max(abs(F));
    result.max_r = max(abs(r));

    result.completed = ...
        isempty(event_time) && ...
        t(end) >= tspan(end) - 1e-10*max(1, abs(tspan(end)));

    if ~result.completed
        return;
    end

    tail_start = tspan(end) - balance.tail_duration;
    tail_indices = t >= tail_start;

    if ~any(tail_indices)
        tail_indices(end) = true;
    end

    result.tail_max_theta_dot = ...
        max(abs(theta_dot(tail_indices)));

    result.tail_max_r_dot = ...
        max(abs(r_dot(tail_indices)));

    result.tail_max_surface_error = ...
        max(abs(s(tail_indices)));

    result.tail_max_surface_speed = ...
        max(abs(s_dot(tail_indices)));

    result.tail_max_theta = ...
        max(abs(theta(tail_indices)));

    result.tail_max_r = ...
        max(abs(r(tail_indices)));

    result.stationary = ...
        result.tail_max_theta_dot <= balance.max_theta_dot && ...
        result.tail_max_r_dot <= balance.max_r_dot && ...
        result.tail_max_surface_error <= balance.max_surface_error && ...
        result.tail_max_surface_speed <= balance.max_surface_speed;

    result.origin_converged = ...
        result.stationary && ...
        result.tail_max_theta <= balance.max_final_theta && ...
        result.tail_max_r <= balance.max_final_r;
end

function printNominalDiagnostics(gains, result, balance)

    fprintf('\nNominal-gain diagnostic before Monte Carlo\n');
    fprintf('  gains [k1, d1, k_theta, d_theta]\n');
    fprintf('        = [%.6g, %.6g, %.6g, %.6g]\n', ...
        gains(1), gains(2), gains(3), gains(4));
    fprintf('  final time                 = %.6f s\n', ...
        result.final_time);
    fprintf('  simulation failed          = %d\n', result.failed);
    fprintf('  event stopped              = %d\n', result.event_stopped);
    fprintf('  completed full simulation  = %d\n', result.completed);
    fprintf('  max|F|                     = %.9g N\n', ...
        result.max_force);
    fprintf('  max|r|                     = %.9g m\n', ...
        result.max_r);
    fprintf('  final theta                = %.9g rad\n', ...
        result.final_theta);
    fprintf('  final r                    = %.9g m\n', ...
        result.final_r);
    fprintf('  tail max|theta_dot|        = %.9g  (limit %.9g)\n', ...
        result.tail_max_theta_dot, balance.max_theta_dot);
    fprintf('  tail max|r_dot|            = %.9g  (limit %.9g)\n', ...
        result.tail_max_r_dot, balance.max_r_dot);
    fprintf('  tail max|s|                = %.9g  (limit %.9g)\n', ...
        result.tail_max_surface_error, balance.max_surface_error);
    fprintf('  tail max|s_dot|            = %.9g  (limit %.9g)\n', ...
        result.tail_max_surface_speed, balance.max_surface_speed);
    fprintf('  tail max|theta|            = %.9g  (origin limit %.9g)\n', ...
        result.tail_max_theta, balance.max_final_theta);
    fprintf('  tail max|r|                = %.9g  (origin limit %.9g)\n', ...
        result.tail_max_r, balance.max_final_r);
    fprintf('  stationary on curve        = %d\n', result.stationary);
    fprintf('  converged to origin        = %d\n\n', ...
        result.origin_converged);

    if ~result.completed
        warning( ...
            'MC_EquilibriumCurve:NominalDidNotComplete', ...
            ['The current gains did not complete the full simulation. ' ...
             'Inspect the diagnostic before running 100,000 samples.']);
    end
end

function F = equilibriumCurveController( ...
        ~, z, par, C_eq, ...
        k1, d1, k_theta, d_theta, force_guard)

    theta = z(1);
    theta_dot = z(2);
    r = z(3);
    r_dot = z(4);

    cos_theta = cos(theta);

    if ~isfinite(cos_theta) || abs(cos_theta) < 1e-6
        error( ...
            'equilibriumCurveController:TanSingularity', ...
            'cos(theta) is too close to zero.');
    end

    sec2_theta = 1/(cos_theta^2);

    s = r - C_eq*tan(theta);
    s_dot = r_dot - C_eq*sec2_theta*theta_dot;

    F = ...
        par.m_rod*par.g*sin(theta) ...
        - k1*s ...
        - d1*s_dot ...
        + k_theta*theta ...
        + d_theta*theta_dot;

    if ~isfinite(F) || abs(F) > force_guard
        error( ...
            'equilibriumCurveController:ForceGuard', ...
            'Requested force is nonfinite or exceeds the simulation guard.');
    end
end

function [value, isterminal, direction] = stopEvents( ...
        ~, z, fall_limit, rod_guard)

    value = [
        fall_limit - abs(z(1));
        rod_guard - abs(z(3))
    ];

    isterminal = [1; 1];
    direction = [-1; -1];
end

function updateParallelProgress( ...
        completed_batch, number_of_samples, progress_interval)

    persistent completed_count next_report

    if isempty(completed_count)
        completed_count = 0;
        next_report = progress_interval;
    end

    completed_count = completed_count + completed_batch;

    while completed_count >= next_report
        fprintf( ...
            'Monte Carlo progress: %d / %d\n', ...
            min(next_report, number_of_samples), ...
            number_of_samples);

        next_report = next_report + progress_interval;
    end
end

function [metric_map, x_centers, y_centers, sample_count] = ...
        makeBinnedMap( ...
            x, y, metric, ...
            x_min, x_max, y_min, y_max, ...
            number_of_bins, statistic_name, minimum_sample_count)

    x_edges = linspace(x_min, x_max, number_of_bins + 1);
    y_edges = linspace(y_min, y_max, number_of_bins + 1);

    x_centers = 0.5*(x_edges(1:end-1) + x_edges(2:end));
    y_centers = 0.5*(y_edges(1:end-1) + y_edges(2:end));

    x_bin = discretize(x, x_edges);
    y_bin = discretize(y, y_edges);

    valid = ...
        isfinite(x_bin) & ...
        isfinite(y_bin) & ...
        isfinite(metric);

    x_bin = x_bin(valid);
    y_bin = y_bin(valid);
    metric = metric(valid);

    linear_bin = sub2ind( ...
        [number_of_bins, number_of_bins], ...
        y_bin, ...
        x_bin);

    switch lower(statistic_name)
        case 'median'
            statistic_function = @median;
        case 'minimum'
            statistic_function = @min;
        case 'maximum'
            statistic_function = @max;
        otherwise
            error( ...
                'makeBinnedMap:UnknownStatistic', ...
                'Unknown heat-map statistic: %s', ...
                statistic_name);
    end

    map_vector = accumarray( ...
        linear_bin, ...
        metric, ...
        [number_of_bins^2, 1], ...
        statistic_function, ...
        NaN);

    count_vector = accumarray( ...
        linear_bin, ...
        1, ...
        [number_of_bins^2, 1], ...
        @sum, ...
        0);

    metric_map = reshape( ...
        map_vector, ...
        number_of_bins, ...
        number_of_bins);

    sample_count = reshape( ...
        count_vector, ...
        number_of_bins, ...
        number_of_bins);

    metric_map(sample_count < minimum_sample_count) = NaN;
end

function plotHeatmapGroup( ...
        k1_centers, d1_centers, k1_d1_map, ...
        k_theta_centers, d_theta_centers, ktheta_dtheta_map, ...
        nominal_gains, reference_limit, statistic_name, ...
        figure_title, colorbar_label)

    all_finite_values = [
        k1_d1_map(isfinite(k1_d1_map));
        ktheta_dtheta_map(isfinite(ktheta_dtheta_map))
    ];

    if isempty(all_finite_values)
        color_limits = [];
    else
        color_limits = [
            min(all_finite_values), ...
            max(all_finite_values)
        ];

        if color_limits(1) == color_limits(2)
            padding = max(1e-12, 0.01*abs(color_limits(1)));
            color_limits = color_limits + [-padding, padding];
        end
    end

    figure( ...
        'Name', figure_title, ...
        'Color', 'w');

    tiledlayout( ...
        1, 2, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    axes_1 = nexttile;

    plotSingleHeatmap( ...
        axes_1, ...
        k1_centers, ...
        d1_centers, ...
        k1_d1_map, ...
        nominal_gains(1), ...
        nominal_gains(2), ...
        reference_limit, ...
        color_limits, ...
        'k1 (N/m)', ...
        'd1 (N s/m)', ...
        sprintf('(k1, d1), %s over other gains', statistic_name), ...
        colorbar_label);

    axes_2 = nexttile;

    plotSingleHeatmap( ...
        axes_2, ...
        k_theta_centers, ...
        d_theta_centers, ...
        ktheta_dtheta_map, ...
        nominal_gains(3), ...
        nominal_gains(4), ...
        reference_limit, ...
        color_limits, ...
        'k_theta (N/rad)', ...
        'd_theta (N s/rad)', ...
        sprintf( ...
            '(k_theta, d_theta), %s over other gains', ...
            statistic_name), ...
        colorbar_label);

    sgtitle(figure_title, 'Interpreter', 'none');
end

function plotSingleHeatmap( ...
        axes_handle, x_centers, y_centers, metric_map, ...
        nominal_x, nominal_y, reference_limit, color_limits, ...
        x_label, y_label, tile_title, colorbar_label)

    image_handle = imagesc( ...
        axes_handle, ...
        x_centers, ...
        y_centers, ...
        metric_map);

    set(axes_handle, ...
        'YDir', 'normal', ...
        'Color', [0.82, 0.82, 0.82], ...
        'Layer', 'top');

    set(image_handle, ...
        'AlphaData', isfinite(metric_map));

    colormap(axes_handle, parula(256));

    if ~isempty(color_limits)
        caxis(axes_handle, color_limits);
    end

    colorbar_handle = colorbar(axes_handle);
    colorbar_handle.Label.String = colorbar_label;
    colorbar_handle.Label.Interpreter = 'none';

    hold(axes_handle, 'on');

    finite_values = metric_map(isfinite(metric_map));
    legend_handles = gobjects(0, 1);

    if ~isempty(finite_values) && ...
       min(finite_values) <= reference_limit && ...
       max(finite_values) >= reference_limit

        [~, limit_contour] = contour( ...
            axes_handle, ...
            x_centers, ...
            y_centers, ...
            metric_map, ...
            [reference_limit, reference_limit], ...
            'k--', ...
            'LineWidth', 1.8, ...
            'DisplayName', 'Hardware limit');

        legend_handles(end + 1) = limit_contour;
    end

    if nominal_x >= min(x_centers) && ...
       nominal_x <= max(x_centers) && ...
       nominal_y >= min(y_centers) && ...
       nominal_y <= max(y_centers)

        nominal_marker = plot( ...
            axes_handle, ...
            nominal_x, ...
            nominal_y, ...
            'wo', ...
            'MarkerFaceColor', 'k', ...
            'MarkerSize', 7, ...
            'LineWidth', 1.3, ...
            'DisplayName', 'Current gains');

        legend_handles(end + 1) = nominal_marker;
    end

    grid(axes_handle, 'on');
    box(axes_handle, 'on');

    xlabel(axes_handle, x_label, 'Interpreter', 'none');
    ylabel(axes_handle, y_label, 'Interpreter', 'none');
    title(axes_handle, tile_title, 'Interpreter', 'none');

    if ~isempty(legend_handles)
        legend( ...
            axes_handle, ...
            legend_handles, ...
            'Location', ...
            'best');
    end

    hold(axes_handle, 'off');
end
