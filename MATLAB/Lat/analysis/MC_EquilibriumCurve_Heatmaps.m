%% Four-gain Monte Carlo study for the equilibrium-curve controller
%
% Controller:
%
%   s     = r - C_eq*tan(theta)
%   s_dot = r_dot - C_eq*sec(theta)^2*theta_dot
%
%   F = m*g*sin(theta)
%       - k1*s
%       - d1*s_dot
%       + k_theta*theta
%       + d_theta*theta_dot
%
% All four gains are sampled independently.  Because a four-dimensional
% result cannot be displayed directly in one two-dimensional heat map, the
% script creates two projections for each performance metric:
%
%   1. (k1, d1), marginalizing over k_theta and d_theta
%   2. (k_theta, d_theta), marginalizing over k1 and d1
%
% Every sample is simulated with the nonlinear model.  Only samples that
% satisfy the balance criteria contribute to the heat maps.

%% 1. System parameters

par = LatParam();

m = par.m_rod;
R = par.R;
g = par.g;
G = par.G;

C_eq = (G + m*g*R)/(m*g);

%% 2. Monte Carlo gain ranges
%
% Gain order used throughout the script:
%   [k1, d1, k_theta, d_theta]

number_of_samples = 100000;
random_seed = 1;

gain_min = [
    200, ... % k1      [N/m]
    5,   ... % d1      [N*s/m]
    0,   ... % k_theta [N/rad]
    0        % d_theta [N*s/rad]
];

gain_max = [
    1400, ... % k1      [N/m]
    100,  ... % d1      [N*s/m]
    80,   ... % k_theta [N/rad]
    30        % d_theta [N*s/rad]
];

% Current gains, shown by the black-centered white markers.
nominal_gains = [800, 40, 20, 5];

% Four-dimensional uniform sampling can miss a narrow stable neighborhood.
% Use part of the samples globally and part near the known working gains.
global_sample_fraction = 0.50;

local_half_range = [
    300, ... % k1 half-range around nominal [N/m]
    20,  ... % d1 half-range around nominal [N*s/m]
    20,  ... % k_theta half-range around nominal [N/rad]
    5       % d_theta half-range around nominal [N*s/rad]
];

rng(random_seed);

number_of_global_samples = round( ...
    global_sample_fraction*number_of_samples);

number_of_local_samples = ...
    number_of_samples - number_of_global_samples;

global_gain_samples = gain_min + ...
    rand(number_of_global_samples, 4).*(gain_max - gain_min);

local_gain_samples = nominal_gains + ...
    (2*rand(number_of_local_samples, 4) - 1).*local_half_range;

local_gain_samples = max( ...
    gain_min, ...
    min(gain_max, local_gain_samples));

gain_samples = [
    global_gain_samples;
    local_gain_samples
];

% Mix global and local samples, then force inclusion of the current gains.
gain_samples = gain_samples(randperm(number_of_samples), :);
gain_samples(1, :) = nominal_gains;

k1_samples = gain_samples(:, 1);
d1_samples = gain_samples(:, 2);
k_theta_samples = gain_samples(:, 3);
d_theta_samples = gain_samples(:, 4);

%% 3. Initial condition
%
% State order used by LatModel_SignCorrection:
%   z = [theta; theta_dot; r; r_dot]

theta0 = 0.10;  % rad
theta_dot0 = 0; % rad/s
r0 = 0;         % m
r_dot0 = 0;     % m/s

z0 = [
    theta0;
    theta_dot0;
    r0;
    r_dot0
];

%% 4. Simulation and balance settings

tspan = [0, 30];

% Reference hardware limits.  The controller is not saturated during the
% Monte Carlo study because the goal is to measure the force that each gain
% tuple actually requests.
hardware_force_limit = 27.6; % N
hardware_rod_limit = 0.10;   % m

% Terminate clearly invalid simulations early.
fall_limit = 27*pi/180;       % rad
simulation_rod_guard = 2.0;   % m
simulation_force_guard = 1e4; % N

% The selection mode controls which samples are used in the heat maps.
%
%   'completed'  - completed 30 s without a fall/rod-guard event
%   'stationary' - completed and nearly stationary on the curve
%   'origin'     - stationary and close to the upright origin
%
% Start with 'completed'.  The summary still reports all three levels, so a
% stricter mode can be selected later without changing the simulations.
balance.selection_mode = 'completed';

% Thresholds for the stricter stationary/origin classifications.
balance.tail_duration = 2.0;        % s
balance.max_theta_dot = 0.02;       % rad/s
balance.max_r_dot = 0.02;           % m/s
balance.max_surface_error = 0.005;  % m
balance.max_surface_speed = 0.02;   % m/s

balance.max_final_theta = 1.0*pi/180; % rad
balance.max_final_r = 0.01;            % m

ode_options = odeset( ...
    'RelTol', 1e-5, ...
    'AbsTol', 1e-7, ...
    'MaxStep', 0.02, ...
    'Events', @(t, z) stopEvents( ...
        t, z, fall_limit, simulation_rod_guard));

% Parallel execution is strongly recommended for 100,000 nonlinear runs.
% The script automatically falls back to a normal for-loop if the Parallel
% Computing Toolbox is unavailable.
use_parallel = true;
parallel_available = ...
    ~isempty(ver('parallel')) && ...
    license('test', 'Distrib_Computing_Toolbox');

progress_interval = 5000;
parallel_progress_batch = 100;

%% 5. Diagnose the current nominal controller before the full Monte Carlo run

nominal_result = simulateGainTuple( ...
    par, C_eq, z0, tspan, ode_options, ...
    nominal_gains(1), nominal_gains(2), ...
    nominal_gains(3), nominal_gains(4), ...
    simulation_force_guard, balance);

printNominalDiagnostics(nominal_gains, nominal_result, balance);

%% 6. Allocate Monte Carlo records

max_force_record = nan(number_of_samples, 1);
max_r_record = nan(number_of_samples, 1);
completed_idx = false(number_of_samples, 1);
event_stopped_idx = false(number_of_samples, 1);
stationary_idx = false(number_of_samples, 1);
origin_converged_idx = false(number_of_samples, 1);
simulation_failed_idx = false(number_of_samples, 1);

tail_theta_dot_record = nan(number_of_samples, 1);
tail_r_dot_record = nan(number_of_samples, 1);
tail_surface_error_record = nan(number_of_samples, 1);
tail_surface_speed_record = nan(number_of_samples, 1);
tail_theta_record = nan(number_of_samples, 1);
tail_r_record = nan(number_of_samples, 1);

fprintf('Four-gain equilibrium-curve Monte Carlo study\n');
fprintf('  Samples         = %d\n', number_of_samples);
fprintf('  Global samples  = %d\n', number_of_global_samples);
fprintf('  Local samples   = %d\n', number_of_local_samples);
fprintf('  Initial theta   = %.6f rad\n', theta0);
fprintf('  Initial r       = %.6f m\n', r0);
fprintf('  k1 range        = [%.3f, %.3f] N/m\n', ...
    gain_min(1), gain_max(1));
fprintf('  d1 range        = [%.3f, %.3f] N*s/m\n', ...
    gain_min(2), gain_max(2));
fprintf('  k_theta range   = [%.3f, %.3f] N/rad\n', ...
    gain_min(3), gain_max(3));
fprintf('  d_theta range   = [%.3f, %.3f] N*s/rad\n\n', ...
    gain_min(4), gain_max(4));

%% 7. Run 100,000 nonlinear simulations

if use_parallel && parallel_available

    fprintf('Running with parfor.\n');

    progress_queue = parallel.pool.DataQueue;
    afterEach( ...
        progress_queue, ...
        @(completed_batch) updateParallelProgress( ...
            completed_batch, number_of_samples, progress_interval));

    parfor sample_index = 1:number_of_samples

        gains = gain_samples(sample_index, :);

        result = simulateGainTuple( ...
            par, C_eq, z0, tspan, ode_options, ...
            gains(1), gains(2), gains(3), gains(4), ...
            simulation_force_guard, balance);

        max_force_record(sample_index) = result.max_force;
        max_r_record(sample_index) = result.max_r;
        completed_idx(sample_index) = result.completed;
        event_stopped_idx(sample_index) = result.event_stopped;
        stationary_idx(sample_index) = result.stationary;
        origin_converged_idx(sample_index) = result.origin_converged;
        simulation_failed_idx(sample_index) = result.failed;
        tail_theta_dot_record(sample_index) = result.tail_max_theta_dot;
        tail_r_dot_record(sample_index) = result.tail_max_r_dot;
        tail_surface_error_record(sample_index) = ...
            result.tail_max_surface_error;
        tail_surface_speed_record(sample_index) = ...
            result.tail_max_surface_speed;
        tail_theta_record(sample_index) = result.tail_max_theta;
        tail_r_record(sample_index) = result.tail_max_r;

        if mod(sample_index, parallel_progress_batch) == 0
            send(progress_queue, parallel_progress_batch);
        end
    end

else

    fprintf('Running with a serial for-loop.\n');

    for sample_index = 1:number_of_samples

        gains = gain_samples(sample_index, :);

        result = simulateGainTuple( ...
            par, C_eq, z0, tspan, ode_options, ...
            gains(1), gains(2), gains(3), gains(4), ...
            simulation_force_guard, balance);

        max_force_record(sample_index) = result.max_force;
        max_r_record(sample_index) = result.max_r;
        completed_idx(sample_index) = result.completed;
        event_stopped_idx(sample_index) = result.event_stopped;
        stationary_idx(sample_index) = result.stationary;
        origin_converged_idx(sample_index) = result.origin_converged;
        simulation_failed_idx(sample_index) = result.failed;
        tail_theta_dot_record(sample_index) = result.tail_max_theta_dot;
        tail_r_dot_record(sample_index) = result.tail_max_r_dot;
        tail_surface_error_record(sample_index) = ...
            result.tail_max_surface_error;
        tail_surface_speed_record(sample_index) = ...
            result.tail_max_surface_speed;
        tail_theta_record(sample_index) = result.tail_max_theta;
        tail_r_record(sample_index) = result.tail_max_r;

        if mod(sample_index, progress_interval) == 0 || ...
           sample_index == number_of_samples

            fprintf( ...
                'Monte Carlo progress: %d / %d\n', ...
                sample_index, number_of_samples);
        end
    end
end

%% 8. Monte Carlo summary and sample selection

switch lower(balance.selection_mode)
    case 'completed'
        balanced_idx = completed_idx;
        selection_description = ...
            'completed without a fall or rod-guard event';
    case 'stationary'
        balanced_idx = stationary_idx;
        selection_description = ...
            'stationary on the equilibrium curve';
    case 'origin'
        balanced_idx = origin_converged_idx;
        selection_description = ...
            'stationary near the upright origin';
    otherwise
        error( ...
            'MC_EquilibriumCurve:UnknownSelectionMode', ...
            'Unknown balance.selection_mode: %s', ...
            balance.selection_mode);
end

force_valid_idx = balanced_idx & ...
    max_force_record <= hardware_force_limit;

rod_valid_idx = balanced_idx & ...
    max_r_record <= hardware_rod_limit;

both_valid_idx = force_valid_idx & rod_valid_idx;

fprintf('\nMonte Carlo summary\n');
fprintf('  Total samples:        %d\n', number_of_samples);
fprintf('  Simulation failed:    %d\n', nnz(simulation_failed_idx));
fprintf('  Event stopped:        %d\n', nnz(event_stopped_idx));
fprintf('  Completed 30 s:       %d\n', nnz(completed_idx));
fprintf('  Stationary on curve:  %d\n', nnz(stationary_idx));
fprintf('  Converged to origin:  %d\n', nnz(origin_converged_idx));
fprintf('  Selected mode:        %s\n', balance.selection_mode);
fprintf('  Selected samples:     %d\n', nnz(balanced_idx));
fprintf('  Force-limit valid:    %d\n', nnz(force_valid_idx));
fprintf('  Rod-limit valid:      %d\n', nnz(rod_valid_idx));
fprintf('  Both limits valid:    %d\n', nnz(both_valid_idx));

normalized_demand = max( ...
    max_force_record/hardware_force_limit, ...
    max_r_record/hardware_rod_limit);

normalized_demand(~balanced_idx) = NaN;
finite_score_indices = find(isfinite(normalized_demand));

if ~isempty(finite_score_indices)

    [best_score, local_index] = min( ...
        normalized_demand(finite_score_indices));

    best_index = finite_score_indices(local_index);

    fprintf('\nLowest normalized hardware demand among selected samples\n');
    fprintf('  sample index   = %d\n', best_index);
    fprintf('  k1             = %.9g N/m\n', k1_samples(best_index));
    fprintf('  d1             = %.9g N*s/m\n', d1_samples(best_index));
    fprintf('  k_theta        = %.9g N/rad\n', ...
        k_theta_samples(best_index));
    fprintf('  d_theta        = %.9g N*s/rad\n', ...
        d_theta_samples(best_index));
    fprintf('  max|F|         = %.9g N\n', max_force_record(best_index));
    fprintf('  max|r|         = %.9g m\n', max_r_record(best_index));
    fprintf('  normalized max = %.9g\n', best_score);
else
    fprintf('\nNo sample satisfied selection mode: %s.\n', ...
        balance.selection_mode);
end

