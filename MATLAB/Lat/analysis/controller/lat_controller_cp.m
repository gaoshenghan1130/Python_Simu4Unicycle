function M = lat_controller_cp(t, z, par)

theta     = z(1);
theta_dot = z(2);
r         = z(3);
r_dot     = z(4);

R = par.R; 

error_target = [ ...
    theta; ...
    r - R * theta; ...
    theta_dot; ...
    r_dot - R * theta_dot ...
];

F_guess = 0; 
residual_fun = @(F) [ ...
    (0.028078*F) / 781.4476 *  0.028078- error_target(1); ...
    (-0.028078*F) / 229.6972 * 0.028078 - error_target(2); ...
    (-0.0020286*F^3  + 0.098988*F ) /146.7735 * 0.098988 - error_target(3); ...
    (-0.00034101*F^3 + 0.42735*F) / 41.4447 * 0.42735 - error_target(4) ...
];

options = optimoptions('lsqnonlin', 'Display', 'off', 'FunctionTolerance', 1e-6);

[F_opt, ~] = lsqnonlin(residual_fun, F_guess, [], [], options);

M = F_opt;

end