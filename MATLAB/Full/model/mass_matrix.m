function M = mass_matrix(x,p)
% Five pseudovelocities: [s1 s2 s3 sr sg].
x=x(:);
s1=x(1);
s2=x(2);
s3=x(3);
sr=x(4);
sg=x(5);
psi=x(6);
theta=x(7);
phi=x(8);
r=x(9);
gamma=x(10);
xG=x(11);
yG=x(12);
g=p.g;
R=p.R;
mw=p.mw;
JW1=p.JW1;
JW2=p.JW2;
mr=p.mr;
JR=p.JR;
BR=p.BR;
h=p.h;
mp=p.mp;
JPx=p.JPx;
JPy=p.JPy;
JPz=p.JPz;
BP=p.BP;
M=zeros(5,5);
M(1,1) = JPz + JR + JW2 + R^2*mp + R^2*mw + 2*R*h*mp*cos(gamma) + mr*r^2 + (JPx - JPz + h^2*mp)*cos(gamma)^2;
M(1,3) = -R*h*mp*sin(gamma) + (-JPx + JPz - h^2*mp)*sin(gamma)*cos(gamma);
M(3,1) = M(1,3);
M(2,2) = JW1 + R^2*mp + R^2*mr + R^2*mw;
M(2,3) = -R*mr*r;
M(3,2) = M(2,3);
M(2,5) = R*h*mp*cos(gamma);
M(5,2) = M(2,5);
M(3,3) = JPz + JR + JW2 + mr*r^2 + (JPx - JPz + h^2*mp)*sin(gamma)^2;
M(4,4) = mr;
M(5,5) = JPy + h^2*mp;
end
